/** Rebuild or check the committed Worker bundle from the vendored source. */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { build } from 'esbuild'

const root = fileURLToPath(new URL('../', import.meta.url))
const args = process.argv.slice(2)
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  throw new Error('Usage: node scripts/build-message-signatures.mjs [--check]')
}
const output = 'src/vendor/http-message-signatures.bundle.js'
const result = await build({
  absWorkingDir: root,
  entryPoints: ['scripts/http-message-signatures-entry.mjs'],
  outfile: output,
  bundle: true,
  format: 'esm',
  platform: 'node',
  // The vendored CommonJS library requires these built-ins. Checked-in ESM
  // shims keep the Worker bundle free of unsupported dynamic require calls.
  alias: {
    crypto: './scripts/vendor-node-shims/crypto.mjs',
    constants: './scripts/vendor-node-shims/constants.mjs'
  },
  target: 'es2022',
  legalComments: 'inline',
  banner: { js: '// Generated by npm run build:vendor. Edit vendor sources or the checked-in entry, not this file.' },
  write: false
})
const generated = result.outputFiles[0].contents
const destination = path.join(root, output)
if (args[0] === '--check') {
  const committed = await readFile(destination)
  if (!committed.equals(generated)) {
    console.error(`${output} is stale. Run npm run build:vendor and commit the result.`)
    process.exitCode = 1
  } else {
    console.log('Vendored message-signature bundle matches its sources.')
  }
} else {
  await writeFile(destination, generated)
  console.log(`Generated ${output}`)
}
