/**
 * Build-time plugin discovery.
 *
 * Cloudflare Workers have no runtime filesystem and cannot dynamically import
 * arbitrary paths at request time — the worker ships as a single bundle. So we
 * discover plugins at build time instead: this script scans `plugins/<name>/`
 * for an `index.js` and writes a static registry (`src/plugins.generated.js`)
 * that the worker imports.
 *
 * Wired into `wrangler.toml` `[build]` (runs on `wrangler dev` and
 * `wrangler deploy`) and into the npm `pretest` hook, so dropping a plugin
 * folder in (or removing one) is reflected on the next build/test with no
 * manual edits. An empty `plugins/` directory yields an empty registry and
 * zero bundle cost.
 */
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pluginsDir = join(root, 'plugins')
const outFile = join(root, 'src', 'plugins.generated.js')

export const generatePluginRegistry = (allowRaw = process.env.PLUGINS) => {
  const discovered = existsSync(pluginsDir)
    ? readdirSync(pluginsDir)
      .filter((name) => {
        const entry = join(pluginsDir, name)
        return statSync(entry).isDirectory() && existsSync(join(entry, 'index.js'))
      })
      .sort()
    : []

  // Optional build-time allowlist via the PLUGINS env var, so a build can include
  // a subset of the discovered plugins without touching the folders (used by the
  // e2e matrix to exercise plugin-presence combinations). Comma-separated names;
  // an empty value selects no plugins; leaving PLUGINS unset includes all.
  let names = discovered
  if (allowRaw !== undefined) {
    const allow = allowRaw.split(',').map((s) => s.trim()).filter(Boolean)
    names = discovered.filter((name) => allow.includes(name))
    const missing = allow.filter((name) => !discovered.includes(name))
    if (missing.length) {
      console.warn(`[generate-plugins] requested plugin(s) not found: ${missing.join(', ')}`)
    }
  }

  const importLines = names
    .map((name, i) => `import plugin${i} from '../plugins/${name}/index.js'`)
    .join('\n')
  const listBody = names.map((_, i) => `plugin${i}`).join(', ')

  const content = `// AUTO-GENERATED by scripts/generate-plugins.mjs — do not edit by hand.
// Regenerated on every build ([build] in wrangler.toml) and before tests (pretest).
${importLines}

export const plugins = [${listBody}]
`
  return { names, content }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { names, content } = generatePluginRegistry()
  writeFileSync(outFile, content)
  const filterNote = process.env.PLUGINS !== undefined ? ' (filtered by PLUGINS)' : ''
  console.log(`[generate-plugins] wrote ${names.length} plugin(s): ${names.join(', ') || '(none)'}${filterNote}`)
}
